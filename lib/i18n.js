/** Every language with localized pages, in the order language links are shown. */
export const LOCALES = { de: DE, es: ES, fr: FR, ja: JA, nl: NL, pt: PT };
export const LOCALE_CODES = Object.keys(LOCALES);
const ALL = { en: EN, ...LOCALES };

export const isLocale = (code) => Object.hasOwn(LOCALES, code);
export const localeData = (code) => ALL[code] || EN;

/** A widget string for a locale, falling back to English. */
export function widgetString(locale, key, vars) {
  const l = localeData(locale).widget;
  const s = l[key] ?? EN.widget[key];
  return vars ? tpl(s, vars) : s;
}

/** A widget label from a nested table (styles, nameStyles, bioTones, nameRules), or the English fallback. */
export const widgetLabel = (locale, table, id, fallback) => localeData(locale).widget[table]?.[id] ?? fallback;

/** A page-chrome string for a locale. */
export function pageString(locale, key, vars) {
  const s = localeData(locale).page[key] ?? EN.page[key];
  return vars ? tpl(s, vars) : s;
}

/** Number formatting per language (2.200 in German and Dutch, 2 200 in French). */
export const formatNumber = (locale, n) => Number(n).toLocaleString(locale === 'en' ? 'en-US' : locale);

/** URL of a page in a language: /tools/x → /de/tools/x. */
export const localePath = (locale, path) => (locale === 'en' ? path : `/${locale}${path === '/' ? '' : path}`);
